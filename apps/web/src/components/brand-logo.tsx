type LogoMarkProps = Omit<SVGProps<SVGSVGElement>, "viewBox" | "fill"> & {
  size: number;
  first?: string;
  second?: string;
  strokeWidth?: number;
};

/**
 * A lowercase m drawn as two arches. One arch per word; the second takes the
 * accent. `first`/`second` exist for the on-dark, mono and "don't" variants.
 */
export function LogoMark({
  size,
  first = MARK_INK,
  second = MARK_ACCENT,
  strokeWidth = 7,
  ...props
}: LogoMarkProps) {
  return (
    <svg
      aria-hidden="true"
      fill="none"
      height={size}
      viewBox="0 0 64 64"
      width={size}
      {...props}
    >
      <path
        d={FIRST_ARCH}
        stroke={first}
        strokeLinecap="round"
        strokeLinejoin="round"
        strokeWidth={strokeWidth}
      />
      <path
        d={SECOND_ARCH}
        stroke={second}
        strokeLinecap="round"
        strokeLinejoin="round"
        strokeWidth={strokeWidth}
      />
    </svg>
  );
}

