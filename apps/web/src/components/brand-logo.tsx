/**
 * The wordmark is a graphic: always lowercase, Urbanist 800, tracking
 * -0.03em, with "metrics" in the accent. Colours are fixed for the same
 * reason as the mark; `mono` drops the split for accent grounds. Sized in
 * ems, so a `text-*` class sets its height as it would a line of text.
 */
export function Wordmark({
  className,
  first = MARK_INK,
  second = MARK_ACCENT,
  mono = false,
}: {
  className?: string;
  first?: string;
  second?: string;
  mono?: boolean;
}) {
  return (
    <svg
      aria-label="motormetrics"
      className={cn("h-[1em] shrink-0", className)}
      role="img"
      style={{ width: `${WORDMARK_WIDTH / WORDMARK_EM}em` }}
      viewBox={`0 0 ${WORDMARK_WIDTH} ${WORDMARK_EM}`}
    >
      <path d={MOTOR_PATH} fill={first} />
      <path d={METRICS_PATH} fill={mono ? first : second} />
    </svg>
  );
}
